"""Recover and check fixed name mappings using data only; never execute sample code."""
import argparse
import ctypes
import hashlib
import json
from pathlib import Path
import struct

from recovered.text.decode_text_table import decode_table, scan_sensitive_candidates

IMAGE_SHA256 = "dec96fd4c691d45349ff50f6f76d60fa8e48f02e8f0dc50b72454adef36b000a"
TABLES = [("mode1_names", 0x6A08D0, 81, 6), ("mode3_names", 0x6A1800, 17, 2),
          ("mode4_names", 0x6A1910, 8, 2), ("mode5_names", 0x6A1990, 4, 2)]


def name_hash(value):
    result = 0xCCA3D13B6510FEAB
    for byte in value:
        result = ((result ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return result


def recover(image):
    if hashlib.sha256(image).hexdigest() != IMAGE_SHA256:
        raise ValueError("unsupported client image hash")
    records, _ = decode_table(image)
    strings = {record.key: record.text for record in records}
    inputs = {}
    for record in records:
        inputs.setdefault(name_hash(record.raw), set()).add(record.text)
    tables = {}
    output = ["// Generated by tools/recover_name_mappings.py; source hash in evidence/name-mappings.json."]
    for name, rva, count, width in TABLES:
        raw = image[rva:rva + count * width * 8]
        rows = list(struct.iter_unpack("<" + "Q" * width, raw))
        if any(a[0] >= b[0] for a, b in zip(rows, rows[1:])):
            raise ValueError("mapping hashes not strictly sorted")
        recovered = []
        output.append(f"constexpr {'MultiMapping' if width == 6 else 'SingleMapping'} {name}[] = {{")
        for hash_value, *keys in rows:
            candidates = inputs.get(hash_value, set())
            if len(candidates) != 1:
                raise ValueError("mapping input is missing or ambiguous")
            source = next(iter(candidates))
            names = [strings[key] for key in keys]
            if any(not name.isascii() or '\0' in name for name in [source, *names]):
                raise ValueError("unexpected non-ASCII or NUL in mapping")
            if scan_sensitive_candidates([source, *names])[1]:
                raise ValueError("potential sensitive mapping value; export stopped")
            values = ", ".join(json.dumps(value) for value in names)
            if width == 6:
                values = "{" + values + "}"
            output.append(f"    {{0x{hash_value:016x}ULL, {values}}},")
            recovered.append((source, names))
        output.append("};")
        tables[name] = recovered
    return "\n".join(output) + "\n", tables


def verify_native(library, tables):
    native = ctypes.CDLL(str(library.resolve()))
    native.recovered_mapped_name.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_int32, ctypes.c_uint32]
    native.recovered_mapped_name.restype = ctypes.c_char_p
    comparisons = 0
    # Enumerate all extracted inputs, override precedence, and mode/namespace boundaries.
    sources = {source for rows in tables.values() for source, _ in rows}
    sources.update(["", "unmapped/Example", "nonascii/\u00ff"])
    expected_tables = {name: dict(rows) for name, rows in tables.items()}
    for source in sorted(sources):
        for mode in [-1, 0, 1, 2, 3, 4, 5, 6, 0x7FFFFFFF]:
            for namespace in [0, 1, 2, 3, 4, 5, 0xFFFFFFFF]:
                expected = None
                if mode == 1 and namespace < 5:
                    values = expected_tables["mode1_names"].get(source)
                    if values is not None:
                        expected = values[namespace]
                elif mode >= 3 and namespace == 1:
                    for threshold in [5, 4, 3]:
                        if mode >= threshold and source in expected_tables[f"mode{threshold}_names"]:
                            expected = expected_tables[f"mode{threshold}_names"][source][0]
                            break
                encoded = source.encode()
                actual = native.recovered_mapped_name(encoded, len(encoded), mode, namespace)
                if actual != (None if expected is None else expected.encode()):
                    raise AssertionError(f"mapping mismatch: mode {mode}, namespace {namespace}")
                comparisons += 1
    return comparisons


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--library", type=Path)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    source, tables = recover(args.image.read_bytes())
    if args.check:
        if args.output.read_text() != source:
            raise SystemExit("generated name data differs from extracted tables")
    else:
        args.output.write_text(source)
    comparisons = verify_native(args.library, tables) if args.library else 0
    report = {"mode": "static_data_and_reconstructed_cpp", "image_sha256": IMAGE_SHA256,
              "tables": [{"rva": hex(rva), "records": count, "columns": width - 1}
                         for _, rva, count, width in TABLES],
              "native_comparisons": comparisons, "mismatches": 0,
              "sample_instructions_executed": False,
              "limitation": "Numeric modes only; no original-code execution, game version detection or Minecraft startup"}
    if args.report:
        args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))
